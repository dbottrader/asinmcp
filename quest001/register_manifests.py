#!/usr/bin/env python3
"""Emit the SQL data migration that registers manifest.json / manifest-test.json
and appends each quest's genesis chronicle record (seq 0, event
manifest_registered). record_hash = seal({quest_id, seq, event, payload,
prev_hash, created_at}) — identical to core.ts recordHash()."""
import hashlib, json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from verify_quest001 import seal  # noqa: E402

CREATED_AT = "2026-11-14T16:00:00.000Z"
out = ["-- generated by quest001/register_manifests.py"]
for name in ("manifest.json", "manifest-test.json"):
    b = open(os.path.join(HERE, name), "rb").read()
    text = b.decode("utf-8")
    assert "$m$" not in text
    m = json.loads(text)
    msha = hashlib.sha256(b).hexdigest()
    payload = {"manifest_sha256": msha, "spec_sha256": m["spec"]["sha256"],
               "claim_url": m["claim"]["url"], "claim_sha256": m["claim"]["sha256"],
               "claim_bytes": m["claim"]["bytes"], "deadline": m["deadline"], "is_test": m["is_test"]}
    rec = {"quest_id": m["quest_id"], "seq": 0, "event": "manifest_registered",
           "payload": payload, "prev_hash": "0" * 64, "created_at": CREATED_AT}
    rh = seal(rec)
    out.append(f"""insert into public.quest_manifests (quest_id, version, manifest_text, manifest, manifest_sha256, valid_from, deadline, is_test)
values ('{m['quest_id']}', {m['version']}, $m${text}$m$, $m${text}$m$::jsonb, '{msha}', '{m['valid_from']}', '{m['deadline']}', {str(m['is_test']).lower()});
insert into public.quest_chronicle (quest_id, seq, event, payload, prev_hash, record_hash, created_at, is_test)
values ('{m['quest_id']}', 0, 'manifest_registered', $p${json.dumps(payload, sort_keys=True)}$p$::jsonb, '{'0'*64}', '{rh}', '{CREATED_AT}', {str(m['is_test']).lower()});""")
    print(f"-- {m['quest_id']} manifest {msha} genesis {rh}", file=sys.stderr)
out.append("""do $$ begin
  if exists (select 1 from public.quest_manifests where encode(sha256(convert_to(manifest_text, 'UTF8')), 'hex') <> manifest_sha256)
  then raise exception 'manifest_text bytes do not match manifest_sha256'; end if;
end $$;""")
print("\n".join(out))
